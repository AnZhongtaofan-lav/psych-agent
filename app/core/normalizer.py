# -*- coding: utf-8 -*-
"""
文本归一化模块 —— 风险匹配与 PII 检测的共同前置。

为什么必须归一化（安全视角）：
    高危用户（或有意的绕过者）会使用变体表达危机内容：
        "不想huo了"   （拼音混写）
        "想 4 了"     （谐音数字）
        "不想 活了"   （插空拆词）
        "不想活了！！！"（全角标点）
    若不做归一化，规则词典全部失效。因此归一化是整个风险体系的
    【第一道防线】，任何风险匹配必须基于归一化后的文本。

归一化流水线（顺序固定，不可调整）：
    1. NFKC 兼容分解（统一特殊 Unicode 形态）
    2. 全角 → 半角
    3. 谐音/拼音映射（数字谐音：4→s？不——详见下方映射表设计说明）
    4. 去除汉字/字母之间的插空
    5. 转小写
"""

from __future__ import annotations

import re
import unicodedata
from functools import lru_cache

# ============================================================
# 谐音与拼音映射表
# ------------------------------------------------------------
# 设计说明：
# - 危机词的常见绕过方式是"同音字替换"（活→huo、死→4/si/s）
# - 映射是"多对一"的归并：把变体统一映射到标准字，词典只存标准字
# - 单字映射必须谨慎：把所有"4"映射成"死"会误伤"我有4个苹果"
#   因此采用【上下文白名单】策略——只在危机短语级别做映射
#   （见 _CONTEXTUAL_REPLACEMENTS），单字映射仅限无歧义的全角/符号变体
# ============================================================

# 单字符无歧义映射：仅当该字符几乎不构成正常中文语义时才纳入
# （拼音字母本身不做单字映射，避免破坏正常英文/拼音输入）
_HOMOPHONE_MAP: dict[str, str] = {
    "ｓ": "s",   # 全角字母 → 半角（由 NFKC 覆盖，此处冗余保险）
    "４": "4",   # 全角数字
}

# ------------------------------------------------------------
# 上下文短语级映射：【变体短语 → 标准短语】
# 这是反绕过的核心。全部条目在"归一化后的小写文本"上做子串替换。
# 每一条都对应真实绕过手法，新增变体时应补充到 resources/risk_lexicon.json
# 的 variants 分组（词典负责"命中"，本表负责"翻译成词典能懂的话"）。
# ------------------------------------------------------------
_CONTEXTUAL_REPLACEMENTS: tuple[tuple[str, str], ...] = (
    # --- 谐音数字：4 ≈ 死（仅在死亡相关短语上下文中出现） ---
    ("想4", "想死"),
    ("想 4", "想死"),   # 汉字与数字间插空变体（"想 4 了"）
    ("4了", "死了"),
    ("求4", "求死"),
    ("求 4", "求死"),
    ("寻4", "寻死"),
    # --- 拼音首字母缩写：s ≈ 死（"想s了"式绕过） ---
    ("想s", "想死"),
    ("想 s", "想死"),
    ("求s", "求死"),
    # --- 拼音混写：huo ≈ 活、si ≈ 死、sha ≈ 杀 ---
    ("不想huo", "不想活"),
    ("不 想huo", "不想活"),
    ("huo不下去", "活不下去"),
    ("不xiang活", "不想活"),
    ("bu想活", "不想活"),
    ("bu想huo", "不想活"),
    ("不 想 活", "不想活"),
    # --- 星号/符号自掩（用户自己打码试图绕过） ---
    ("不*活", "不想活"),
    ("不想**了", "不想活了"),
    # --- 拉丁变体 ---
    ("emo到想si", "emo到想死"),
)

# 插空模式：单个空格夹在两个中文字符之间（"不想 活了" → "不想活了"）
_CJK_SPACE_CJK_RE = re.compile(r"([\u4e00-\u9fa5])[ \t]+([\u4e00-\u9fa5])")


def _remove_intra_cjk_spaces(text: str) -> str:
    """去除相邻汉字之间的空格（含连续多空格，通过重复替换收敛）。

    注意：只去除"汉字之间的"空格，保留英文单词间的正常空格
    （"i am sad" 不能变成 "iamsad"，否则英文风险词反而匹配不到）。
    """

    prev = None
    current = text
    # 循环处理 "汉 汉 汉" 这类多空格连续场景，直至稳定
    while prev != current:
        prev = current
        current = _CJK_SPACE_CJK_RE.sub(r"\1\2", current)
    return current


@lru_cache(maxsize=4096)
def normalize(text: str) -> str:
    """文本归一化主入口（带 LRU 缓存：同一文本重复对话场景高效）。

    流水线（顺序固定）：
        1. NFKC 兼容分解：统一全角/兼容字符形态
        2. 转小写（英文风险词与拼音变体统一大小写）
        3. 上下文短语级谐音映射（反绕过核心）
        4. 去除汉字间插空

    参数:
        text: 原始用户输入

    返回:
        归一化后的文本（仅用于规则匹配，不用于展示与存储）
    """
    if not text:
        return ""

    # 1. NFKC：全角字母/数字/符号 → 半角标准形（４→4、ｓ→s 等）
    result = unicodedata.normalize("NFKC", text)

    # 2. 小写化：统一英文与拼音变体大小写
    result = result.lower()

    # 3. 短语级谐音/拼音映射（在插空去除【前】执行：
    #    短语表中的变体本身可能带空格形态，如 "不 想 活"）
    for variant, standard in _CONTEXTUAL_REPLACEMENTS:
        if variant in result:
            result = result.replace(variant, standard)

    # 4. 去除汉字之间的插空："不想 活了" → "不想活了"
    result = _remove_intra_cjk_spaces(result)

    return result
